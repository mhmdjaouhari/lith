const (
	goFile = "ds_gen.go"
	tsFile = "ds.gen.ts"
	// oldTSFile is what dsgen wrote before the DOM constants, values a
	// module imports: Run removes it.
	oldTSFile = "ds.gen.d.ts"
	header    = "Code generated by dsgen from this package's //ds: directives. DO NOT EDIT."
	dsPkg     = "github.com/zweiundeins/lith/site/internal/ds"
)

var (
	rootPattern = regexp.MustCompile(`^[_a-zA-Z][_a-zA-Z0-9]*$`)
	namePattern = regexp.MustCompile(`^[a-z][a-z0-9-]*$`)
)

// signals is a //ds:signals struct.
type signals struct {
	name      string
	st        *types.Struct
	root, ref string
}

// command is a //ds:command payload.
type command struct {
	name       string
	st         *types.Struct
	slug, verb string
}

// Run generates, or with check verifies, the files of the package in dir.
func Run(dir string, check bool) error {
	files, err := Generate(dir)
	if err != nil {
		return err
	}
	var stale []string
	for name, want := range files {
		path := filepath.Join(dir, name)
		if check {
			have, _ := os.ReadFile(path)
			if !bytes.Equal(have, want) {
				stale = append(stale, path)
			}
			continue
		}
		if want == nil {
			if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
				return err
			}
			continue
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		sort.Strings(stale)
		return fmt.Errorf("not current, run go generate: %s", strings.Join(stale, ", "))
	}
	return nil
}

// Generate returns the generated files of the package in dir, by name; a
// nil file is one the package should not have.
func Generate(dir string) (map[string][]byte, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
		Dir:  dir,
		// The generated file may be stale or missing while the rest of
		// the package refers to it: read the package without it. Its
		// type errors do not keep the structs from being read.
		ParseFile: func(fset *token.FileSet, filename string, src []byte) (*ast.File, error) {
			if filepath.Base(filename) == goFile {
				src = []byte("package " + pkgClause(src))
			}
			return parser.ParseFile(fset, filename, src, parser.AllErrors|parser.ParseComments)
		},
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 || pkgs[0].Types == nil {
		return nil, fmt.Errorf("%s: no single package", dir)
	}
	p := pkgs[0]
	var sigs []signals
	var cmds []command
	var doms []domConst
	var vals []valueConst
	for _, f := range p.Syntax {
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if ok && gd.Tok == token.CONST && len(directives(gd.Doc)) > 0 {
				kind, err := constKind(gd)
				if err != nil {
					return nil, err
				}
				if kind == "dom" {
					ds, err := domConsts(p.Types, gd)
					if err != nil {
						return nil, err
					}
					doms = append(doms, ds...)
				} else {
					vs, err := valueConsts(p.Types, gd)
					if err != nil {
						return nil, err
					}
					vals = append(vals, vs...)
				}
				continue
			}
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				for _, args := range directives(doc) {
					obj := p.Types.Scope().Lookup(ts.Name.Name)
					st, ok := obj.Type().Underlying().(*types.Struct)
					if !ok || len(args) == 0 {
						return nil, fmt.Errorf("%s: a //ds: directive on a type that is no struct", ts.Name.Name)
					}
					switch args[0] {
					case "signals":
						s := signals{name: ts.Name.Name, st: st}
						switch len(args) {
						case 1:
						case 3:
							s.root, s.ref = args[1], args[2]
							if !rootPattern.MatchString(s.root) || !token.IsIdentifier(s.ref) {
								return nil, fmt.Errorf("%s: //ds:signals %s %s: a signal name and a Go name", s.name, s.root, s.ref)
							}
						default:
							return nil, fmt.Errorf("%s: //ds:signals [root var]", s.name)
						}
						sigs = append(sigs, s)
					case "command":
						if len(args) != 3 || !namePattern.MatchString(args[1]) || !namePattern.MatchString(args[2]) {
							return nil, fmt.Errorf("%s: //ds:command <slug> <name>", ts.Name.Name)
						}
						cmds = append(cmds, command{name: ts.Name.Name, st: st, slug: args[1], verb: args[2]})
					default:
						return nil, fmt.Errorf("%s: unknown directive //ds:%s", ts.Name.Name, args[0])
					}
				}
			}
		}
	}
	out := map[string][]byte{goFile: nil, tsFile: nil, oldTSFile: nil}
	if len(sigs) == 0 && len(cmds) == 0 && len(doms) == 0 && len(vals) == 0 {
		return out, nil
	}
	g := &gen{pkg: p.Types, imports: map[string]string{}, local: map[string]bool{}}
	for _, s := range sigs {
		g.local[s.name] = true
	}
	if out[goFile], err = g.goSource(p.Name, sigs, cmds, doms); err != nil {
		return nil, err
	}
	if out[tsFile], err = tsSource(sigs, cmds, doms, vals); err != nil {
		return nil, err
	}
	return out, nil
}

// domConst is a //ds:dom constant: a name of the page's markup that the
// templates and the package's TypeScript share.
type domConst struct{ name, value string }

// constKind returns the one directive of a const block: "dom" or "const".
func constKind(gd *ast.GenDecl) (string, error) {
	ds := directives(gd.Doc)
	if len(ds) == 1 && len(ds[0]) == 1 && (ds[0][0] == "dom" || ds[0][0] == "const") {
		return ds[0][0], nil
	}
	var all []string
	for _, args := range ds {
		all = append(all, "//ds:"+strings.Join(args, " "))
	}
	return "", fmt.Errorf("a const block takes //ds:dom or //ds:const alone, not %s", strings.Join(all, ", "))
}

// valueConst is a //ds:const constant, as a JS literal.
type valueConst struct{ name, lit string }

// valueConsts reads a //ds:const const block: exported constants of a
// basic kind (a number, a string, a bool) that the package's controller
// reads as the same values, so that neither side types them again (the
// size of a grid, say).
func valueConsts(pkg *types.Package, gd *ast.GenDecl) ([]valueConst, error) {
	var out []valueConst
	for _, spec := range gd.Specs {
		for _, id := range spec.(*ast.ValueSpec).Names {
			c, ok := pkg.Scope().Lookup(id.Name).(*types.Const)
			if !ok || !id.IsExported() {
				return nil, fmt.Errorf("//ds:const %s: an exported constant", id.Name)
			}
			b, ok := c.Type().Underlying().(*types.Basic)
			if !ok || b.Info()&(types.IsNumeric|types.IsString|types.IsBoolean) == 0 || b.Info()&types.IsComplex != 0 {
				return nil, fmt.Errorf("//ds:const %s: a number, a string or a bool", id.Name)
			}
			var lit string
			switch v := c.Val(); v.Kind() {
			case constant.String:
				lit = fmt.Sprintf("%q", constant.StringVal(v))
			case constant.Int:
				// A JS number holds an integer exactly up to 2^53.
				if n, exact := constant.Int64Val(v); !exact || n > 1<<53 || n < -(1<<53) {
					return nil, fmt.Errorf("//ds:const %s: %s is no exact JS number", id.Name, v)
				}
				lit = v.ExactString()
			case constant.Float:
				f, _ := constant.Float64Val(v)
				lit = strconv.FormatFloat(f, 'g', -1, 64)
			default:
				lit = v.ExactString() // a bool
			}
			out = append(out, valueConst{id.Name, lit})
		}
	}
	return out, nil
}

// domConsts reads a //ds:dom const block: exported string constants, each
// a data- attribute's name, a class, or a custom property (--x).
func domConsts(pkg *types.Package, gd *ast.GenDecl) ([]domConst, error) {
	var out []domConst
	for _, spec := range gd.Specs {
		for _, id := range spec.(*ast.ValueSpec).Names {
			c, ok := pkg.Scope().Lookup(id.Name).(*types.Const)
			if !ok || !id.IsExported() || c.Val().Kind() != constant.String {
				return nil, fmt.Errorf("//ds:dom %s: an exported string constant", id.Name)
			}
			v := constant.StringVal(c.Val())
			if !domPattern.MatchString(v) {
				return nil, fmt.Errorf("//ds:dom %s = %q: a data- attribute, a class or a custom property", id.Name, v)
			}
			out = append(out, domConst{id.Name, v})
		}
	}
	return out, nil
}

var domPattern = regexp.MustCompile(`^(data-[a-z][a-z0-9-]*|--[a-z][a-z0-9-]*|[a-z][a-z0-9_-]*)$`)

// directives returns the //ds: lines of a comment, split into words.
func directives(doc *ast.CommentGroup) [][]string {
	if doc == nil {
		return nil
	}
	var out [][]string
	for _, c := range doc.List {
		if rest, ok := strings.CutPrefix(c.Text, "//ds:"); ok {
			out = append(out, strings.Fields(rest))
		}
	}
	return out
}

type gen struct {
	pkg     *types.Package
	imports map[string]string // path -> name
	local   map[string]bool   // the package's //ds:signals structs
}

func (g *gen) qualifier(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	g.imports[p.Path()] = p.Name()
	return p.Name()
}

// qualified returns the prefix of a name in the package of named: "" or
// "demo.".
func (g *gen) qualified(named *types.Named) string {
	if q := g.qualifier(named.Obj().Pkg()); q != "" {
		return q + "."
	}
	return ""
}

func (g *gen) goSource(pkgName string, sigs []signals, cmds []command, doms []domConst) ([]byte, error) {
	var body bytes.Buffer
	if len(doms) > 0 {
		body.WriteString("\n// dsDOM are the package's //ds:dom constants by name, for dscheck.CheckDOM:\n// each must be on the page the package renders.\nvar dsDOM = map[string]string{\n")
		for _, d := range doms {
			fmt.Fprintf(&body, "\t%q: %s,\n", d.name, d.name)
		}
		body.WriteString("}\n")
	}
	for _, s := range sigs {
		if err := g.refs(&body, s); err != nil {
			return nil, err
		}
	}
	for _, c := range cmds {
		fields, err := jsonFields(c.st)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", c.name, err)
		}
		if f, ok := find(fields, "tab"); !ok || f.typ.String() != "string" {
			return nil, fmt.Errorf("%s: a command's payload carries the page's tab id as `json:\"tab\"`, a string", c.name)
		}
		fmt.Fprintf(&body, "\n// DSCommand names the action %s is the payload of: POST /cmd/%s/%s.\n", c.name, c.slug, c.verb)
		fmt.Fprintf(&body, "func (%s) DSCommand() (slug, name string) { return %q, %q }\n", c.name, c.slug, c.verb)
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// %s\n\npackage %s\n\n", header, pkgName)
	if len(g.imports) > 0 {
		paths := make([]string, 0, len(g.imports))
		for p := range g.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		src.WriteString("import (\n")
		for _, p := range paths {
			fmt.Fprintf(&src, "\t%q\n", p)
		}
		src.WriteString(")\n")
	}
	src.Write(body.Bytes())
	return format.Source(src.Bytes())
}

// refs writes the refs struct of a signals struct and its constructor.
func (g *gen) refs(w *bytes.Buffer, s signals) error {
	ds := g.qualifier(types.NewPackage(dsPkg, "ds"))
	var fields, inits bytes.Buffer
	for i := 0; i < s.st.NumFields(); i++ {
		f := s.st.Field(i)
		if !f.Exported() {
			continue
		}
		key, skip, err := jsonKey(f, s.st.Tag(i))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", s.name, f.Name(), err)
		}
		if skip {
			continue
		}
		named, isNamed := types.Unalias(f.Type()).(*types.Named)
		switch {
		case f.Embedded():
			// encoding/json inlines an embedded struct's fields, so its refs
			// are embedded too, from the constructor next to its type.
			if !isNamed || !g.hasRefs(named) {
				return fmt.Errorf("%s.%s: an embedded field must be a //ds:signals struct", s.name, f.Name())
			}
			q := g.qualified(named)
			fmt.Fprintf(&fields, "\t%s%sRefs\n", q, named.Obj().Name())
			fmt.Fprintf(&inits, "\t\t%sRefs: %sNew%sRefs(path),\n", named.Obj().Name(), q, named.Obj().Name())
		case isNamed && g.hasRefs(named):
			q := g.qualified(named)
			fmt.Fprintf(&fields, "\t%s %s%sRefs\n", f.Name(), q, named.Obj().Name())
			fmt.Fprintf(&inits, "\t\t%s: %sNew%sRefs(path + %q),\n", f.Name(), q, named.Obj().Name(), "."+key)
		default:
			if _, err := (&tsGen{aliases: map[string]string{}}).typ(f.Type(), ""); err != nil {
				return fmt.Errorf("%s.%s: %w", s.name, f.Name(), err)
			}
			typ := types.TypeString(f.Type(), g.qualifier)
			fmt.Fprintf(&fields, "\t%s %s.Ref[%s] // .%s\n", f.Name(), ds, typ, key)
			fmt.Fprintf(&inits, "\t\t%s: %s.NewRef[%s](path + %q),\n", f.Name(), ds, typ, "."+key)
		}
	}
	fmt.Fprintf(w, "\n// %sRefs are the signals of %s, each a ds.Ref.\ntype %sRefs struct {\n%s}\n", s.name, s.name, s.name, fields.String())
	fmt.Fprintf(w, "\n// New%sRefs returns the refs of %s declared under path, such as \"_board\".\nfunc New%sRefs(path string) %sRefs {\n\treturn %sRefs{\n%s\t}\n}\n", s.name, s.name, s.name, s.name, s.name, inits.String())
	if s.root != "" {
		fmt.Fprintf(w, "\n// %s are the page's signals, under $%s.\nvar %s = New%sRefs(%q)\n", s.ref, s.root, s.ref, s.name, s.root)
		fmt.Fprintf(w, "\n// Decl is the data-signals value that declares v under $%s.\nfunc (v %s) Decl() string { return %s.Decl(%q, v) }\n", s.root, s.name, ds, s.root)
	}
	return nil
}

// hasRefs reports whether a named struct is a //ds:signals struct, which
// has a Refs type: one of this package's, or one whose package has its
// constructor.
func (g *gen) hasRefs(named *types.Named) bool {
	if _, ok := named.Underlying().(*types.Struct); !ok {
		return false
	}
	if named.Obj().Pkg() == g.pkg {
		return g.local[named.Obj().Name()]
	}
	return named.Obj().Pkg().Scope().Lookup("New"+named.Obj().Name()+"Refs") != nil
}

type field struct {
	key      string
	typ      types.Type
	optional bool
}

// find returns the field with the JSON key.
func find(fs []field, key string) (field, bool) {
	for _, f := range fs {
		if f.key == key {
			return f, true
		}
	}
	return field{}, false
}

// jsonFields returns a struct's fields in order, by their JSON keys,
// embedded structs inlined as encoding/json does.
func jsonFields(st *types.Struct) ([]field, error) {
	var out []field
	add := func(f field) error {
		if _, dup := find(out, f.key); dup {
			return fmt.Errorf("two fields named %q", f.key)
		}
		out = append(out, f)
		return nil
	}
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() {
			continue
		}
		key, skip, err := jsonKey(f, st.Tag(i))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f.Name(), err)
		}
		if skip {
			continue
		}
		if f.Embedded() {
			inner, ok := f.Type().Underlying().(*types.Struct)
			if !ok {
				return nil, fmt.Errorf("%s: an embedded field must be a struct", f.Name())
			}
			sub, err := jsonFields(inner)
			if err != nil {
				return nil, err
			}
			for _, v := range sub {
				if err := add(v); err != nil {
					return nil, err
				}
			}
			continue
		}
		opt := strings.Contains(reflect.StructTag(st.Tag(i)).Get("json"), ",omitempty")
		if err := add(field{key: key, typ: f.Type(), optional: opt}); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// jsonKey returns a field's JSON key. Every field of the seam has an
// explicit one, but an embedded struct: the name is the contract with the
// page, never Go's case-insensitive matching.
func jsonKey(f *types.Var, tag string) (key string, skip bool, err error) {
	j, ok := reflect.StructTag(tag).Lookup("json")
	name, _, _ := strings.Cut(j, ",")
	switch {
	case name == "-":
		return "", true, nil
	case f.Embedded() && name == "":
		return "", false, nil
	case !ok || name == "":
		return "", false, errors.New("needs a json tag with its name")
	case !rootPattern.MatchString(name):
		return "", false, fmt.Errorf("json name %q is not a JS identifier", name)
	}
	return name, false, nil
}

// pkgClause returns the package name of a Go file's source.
func pkgClause(src []byte) string {
	for _, line := range strings.Split(string(src), "\n") {
		if name, ok := strings.CutPrefix(strings.TrimSpace(line), "package "); ok {
			return strings.TrimSpace(name) + "\n"
		}
	}
	return "main\n"
}
